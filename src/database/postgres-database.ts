import { Pool, PoolClient, QueryResult, QueryResultRow } from "pg";

export class PostgresDatabase {
  readonly schema: string;
  readonly pool: Pool;

  constructor(connectionString: string, schema = "public") {
    if (!connectionString) throw new Error("Falta DATABASE_URL. Configura la conexión PostgreSQL en el archivo .env.");
    if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(schema)) throw new Error("DB_SCHEMA contiene un nombre no válido.");
    this.schema = schema;
    this.pool = new Pool({ connectionString, options: `-c search_path=${schema}` });
  }

  async initialize(): Promise<void> {
    if (this.schema !== "public") {
      await this.pool.query(`CREATE SCHEMA IF NOT EXISTS "${this.schema}"`);
    }
    await this.pool.query(`CREATE TABLE IF NOT EXISTS "${this.schema}".employees (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      document TEXT NOT NULL UNIQUE, first_name TEXT NOT NULL, last_name TEXT NOT NULL,
      position TEXT NOT NULL, salary DOUBLE PRECISION NOT NULL CHECK (salary >= 0),
      status TEXT NOT NULL CHECK (status IN ('activo', 'inactivo')),
      contract_start_date TEXT NOT NULL,
      contract_type TEXT NOT NULL CHECK (contract_type IN ('indefinido', 'fijo', 'obra_labor')),
      contract_status TEXT NOT NULL CHECK (contract_status IN ('vigente', 'finalizado'))
    )`);
    await this.pool.query(`CREATE TABLE IF NOT EXISTS "${this.schema}".employee_history (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      employee_id BIGINT NOT NULL REFERENCES "${this.schema}".employees(id),
      type TEXT NOT NULL CHECK (type IN ('cargo', 'salario', 'estado')),
      previous_value TEXT NOT NULL, new_value TEXT NOT NULL, changed_at TEXT NOT NULL
    )`);
    await this.pool.query(`CREATE INDEX IF NOT EXISTS idx_employee_history_employee_id ON "${this.schema}".employee_history(employee_id)`);
    await this.pool.query(`CREATE TABLE IF NOT EXISTS "${this.schema}".vacations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      employee_id BIGINT NOT NULL REFERENCES "${this.schema}".employees(id),
      start_date TEXT NOT NULL, end_date TEXT NOT NULL,
      status TEXT NOT NULL CHECK (status IN ('pendiente', 'aprobada', 'rechazada')),
      CHECK (end_date >= start_date)
    )`);
    await this.pool.query(`CREATE INDEX IF NOT EXISTS idx_vacations_employee_id ON "${this.schema}".vacations(employee_id)`);
  }

  async transaction<T>(action: (client: PoolClient) => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const result = await action(client);
      await client.query("COMMIT");
      return result;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally { client.release(); }
  }
  query<T extends QueryResultRow = QueryResultRow>(text: string, values?: unknown[]): Promise<QueryResult<T>> { return this.pool.query<T>(text, values); }
  close(): Promise<void> { return this.pool.end(); }
}
